//! Emits C writer headers from protoc's FileDescriptorSet: one header per .proto file holding
//! any of the given root messages or enums, with each root's nested types. zig build gen runs
//! protoc and this, and writes the result to include/utrace/perfetto/.
//!
//! usage: gen <descriptor-set> <VERSION or -> <out-dir> <full name of a root>...

const std = @import("std");
const pb = @import("pb");
const Allocator = std.mem.Allocator;

pub fn main(init: std.process.Init) !void {
    const arena = init.arena.allocator();
    const io = init.io;
    const args = try init.minimal.args.toSlice(arena);
    if (args.len < 5) {
        std.debug.print("usage: {s} <descriptor-set> <VERSION or -> <out-dir> <root>...\n", .{args[0]});
        std.process.exit(2);
    }
    const cwd = std.Io.Dir.cwd();
    const bytes = try cwd.readFileAlloc(io, args[1], arena, .limited(64 << 20));
    // VERSION is "<release tag> <commit>", as tools/vendor-perfetto.sh writes it; "-" for none
    var source: []const u8 = "";
    if (!std.mem.eql(u8, args[2], "-")) {
        var version = std.mem.tokenizeAny(u8, try cwd.readFileAlloc(io, args[2], arena, .limited(4096)), " \n");
        const tag = version.next() orelse fatal("{s} names no release", .{args[2]});
        const commit = version.next() orelse fatal("{s} names no commit", .{args[2]});
        source = try std.fmt.allocPrint(arena, "Perfetto {s} ({s}),\n * ", .{ tag, commit });
    }
    const set = try pb.DescriptorSet.parse(arena, bytes);

    var out_dir = try cwd.createDirPathOpen(io, args[3], .{});
    defer out_dir.close(io);

    var files: std.ArrayList(*const pb.FileDesc) = .empty;
    for (args[4..]) |root| {
        const file = set.fileOf(root) orelse fatal("no top-level message or enum {s}", .{root});
        for (files.items) |f| {
            if (f == file) break;
        } else try files.append(arena, file);
    }
    var names: std.StringHashMapUnmanaged(void) = .empty;
    for (files.items) |file| {
        var g: Gen = .{ .arena = arena, .file = file, .source = source, .names = &names };
        const header = try g.header(args[4..]);
        try out_dir.writeFile(io, .{ .sub_path = try headerName(arena, file.name), .data = header });
    }
}

fn fatal(comptime fmt: []const u8, args: anytype) noreturn {
    std.debug.print("gen: " ++ fmt ++ "\n", args);
    std.process.exit(1);
}

fn headerName(arena: Allocator, proto: []const u8) ![]const u8 {
    const base = std.fs.path.basename(proto);
    const stem = if (std.mem.endsWith(u8, base, ".proto")) base[0 .. base.len - ".proto".len] else base;
    return std.fmt.allocPrint(arena, "{s}.h", .{stem});
}

const Gen = struct {
    arena: Allocator,
    file: *const pb.FileDesc,
    /// Where the protos came from, ending in a line break, or empty
    source: []const u8,
    out: std.ArrayList(u8) = .empty,
    /// Every C identifier emitted to any header, so that two proto names mapping to one fails
    names: *std.StringHashMapUnmanaged(void),

    fn print(g: *Gen, comptime fmt: []const u8, args: anytype) !void {
        try g.out.print(g.arena, fmt, args);
    }

    fn declare(g: *Gen, name: []const u8) ![]const u8 {
        const entry = try g.names.getOrPut(g.arena, name);
        if (entry.found_existing) fatal("{s} would be declared twice", .{name});
        return name;
    }

    /// The C spelling of a type's full name: the package dropped, dots as underscores
    fn cname(g: *Gen, full_name: []const u8) ![]const u8 {
        const local = if (g.file.package.len == 0) full_name else full_name[g.file.package.len + 1 ..];
        const name = try g.arena.dupe(u8, local);
        std.mem.replaceScalar(u8, name, '.', '_');
        return std.fmt.allocPrint(g.arena, "utrace_perfetto_{s}", .{name});
    }

    fn header(g: *Gen, roots: []const []const u8) ![]const u8 {
        const guard = try std.ascii.allocUpperString(g.arena, try headerName(g.arena, g.file.name));
        std.mem.replaceScalar(u8, guard, '.', '_');
        // the names and numbers are Perfetto's, so its license comes along with them
        // REUSE-IgnoreStart
        try g.print("/*\n * SPDX-FileCopyrightText: Simon A. F. Lund <os@safl.dk>\n", .{});
        if (g.source.len > 0) try g.print(" * SPDX-FileCopyrightText: The Android Open Source Project\n", .{});
        try g.print(" *\n * SPDX-License-Identifier: {s}\n */\n", .{if (g.source.len > 0) "BSD-3-Clause AND Apache-2.0" else "BSD-3-Clause"});
        // REUSE-IgnoreEnd
        try g.print(
            \\/*
            \\ * Generated by tools/gen.zig from {s}{s}. Do not edit; run zig build gen.
            \\ */
            \\#ifndef UTRACE_PERFETTO_{s}
            \\#define UTRACE_PERFETTO_{s}
            \\
            \\#include <utrace_pb.h>
            \\
            \\#ifdef __cplusplus
            \\extern "C" {{
            \\#endif
            \\
        , .{ g.source, g.file.name, guard, guard });

        for (g.file.enums) |*e| {
            if (isRoot(roots, e.full_name)) try g.enumType(e, "");
        }
        for (g.file.messages) |*m| {
            if (isRoot(roots, m.full_name)) try g.message(m);
        }

        try g.print(
            \\
            \\#ifdef __cplusplus
            \\}}
            \\#endif
            \\
            \\#endif /* UTRACE_PERFETTO_{s} */
            \\
        , .{guard});
        return tabify(g.arena, g.out.items);
    }

    /// Zig's multiline strings cannot hold tabs, so the templates indent by four spaces and
    /// the C indents by tabs
    fn tabify(arena: Allocator, text: []const u8) ![]const u8 {
        var out: std.ArrayList(u8) = .empty;
        var lines = std.mem.splitScalar(u8, text, '\n');
        var first = true;
        while (lines.next()) |line| {
            if (!first) try out.append(arena, '\n');
            first = false;
            var rest = line;
            while (std.mem.startsWith(u8, rest, "    ")) : (rest = rest[4..]) try out.append(arena, '\t');
            try out.appendSlice(arena, rest);
        }
        return out.items;
    }

    fn isRoot(roots: []const []const u8, full_name: []const u8) bool {
        for (roots) |r| if (std.mem.eql(u8, r, full_name)) return true;
        return false;
    }

    /// Values are scoped like C++: next to the enum, in the enclosing message, or at top level
    fn enumType(g: *Gen, e: *const pb.EnumDesc, scope_full_name: []const u8) !void {
        if (e.values.len == 0) return;
        const prefix = if (scope_full_name.len == 0) "utrace_perfetto" else try g.cname(scope_full_name);
        try g.print("\n/* {s} */\nenum {s} {{\n", .{ e.full_name, try g.declare(try g.cname(e.full_name)) });
        for (e.values) |v| {
            const name = try g.declare(try std.fmt.allocPrint(g.arena, "{s}_{s}", .{ prefix, v.name }));
            try g.print("\t{s} = {d},\n", .{ name, v.number });
        }
        try g.print("}};\n", .{});
    }

    fn message(g: *Gen, m: *const pb.MessageDesc) !void {
        const name = try g.cname(m.full_name);
        for (m.enums) |*e| try g.enumType(e, m.full_name);

        if (m.fields.len > 0) {
            try g.print("\n/* {s} */\nenum {{\n", .{m.full_name});
            for (m.fields) |f| {
                const constant = try g.declare(try std.fmt.allocPrint(g.arena, "{s}_FIELD_{s}", .{ name, f.name }));
                try g.print("\t{s} = {d},\n", .{ constant, f.number });
            }
            try g.print("}};\n", .{});
        }
        for (m.fields) |*f| try g.writer(name, f);
        for (m.nested) |*n| try g.message(n);
    }

    fn writer(g: *Gen, msg_name: []const u8, f: *const pb.FieldDesc) !void {
        const field = try std.fmt.allocPrint(g.arena, "{s}_FIELD_{s}", .{ msg_name, f.name });
        const repeated = f.label == .repeated;

        if (f.type == .message) {
            const func = try g.declare(try std.fmt.allocPrint(g.arena, "{s}_begin_{s}", .{ msg_name, f.name }));
            try g.print(
                \\
                \\/** Opens {s}; close it with utrace_pb_end() */
                \\static inline void
                \\{s}(struct utrace_pb_writer *w)
                \\{{
                \\    utrace_pb_begin(w, {s});
                \\}}
                \\
            , .{ f.name, func, field });
            return;
        }

        const verb = if (repeated and !f.@"packed") "add" else "set";
        const func = try g.declare(try std.fmt.allocPrint(g.arena, "{s}_{s}_{s}", .{ msg_name, verb, f.name }));

        switch (f.type) {
            .string => {
                const func_n = try g.declare(try std.fmt.allocPrint(g.arena, "{s}_n", .{func}));
                try g.print(
                    \\
                    \\static inline void
                    \\{s}(struct utrace_pb_writer *w, const char *s)
                    \\{{
                    \\    utrace_pb_field_string(w, {s}, s);
                    \\}}
                    \\
                    \\static inline void
                    \\{s}(struct utrace_pb_writer *w, const char *s, size_t n)
                    \\{{
                    \\    utrace_pb_field_bytes(w, {s}, s, n);
                    \\}}
                    \\
                , .{ func, field, func_n, field });
                return;
            },
            .bytes => {
                try g.print(
                    \\
                    \\static inline void
                    \\{s}(struct utrace_pb_writer *w, const void *data, size_t n)
                    \\{{
                    \\    utrace_pb_field_bytes(w, {s}, data, n);
                    \\}}
                    \\
                , .{ func, field });
                return;
            },
            .group => fatal("{s}: groups are not supported", .{f.name}),
            else => {},
        }

        const s = scalar(f.type);
        if (f.@"packed") {
            try g.print(
                \\
                \\static inline void
                \\{s}(struct utrace_pb_writer *w, const {s} *v, size_t n)
                \\{{
                \\    size_t i;
                \\
                \\    utrace_pb_begin(w, {s});
                \\    for (i = 0; i < n; ++i) {{
                \\        {s}
                \\    }}
                \\    utrace_pb_end(w);
                \\}}
                \\
            , .{ func, s.ctype, field, try fill(g.arena, s.element, field, "v[i]") });
            return;
        }
        try g.print(
            \\
            \\static inline void
            \\{s}(struct utrace_pb_writer *w, {s} v)
            \\{{
            \\    {s}
            \\}}
            \\
        , .{ func, s.ctype, try fill(g.arena, s.field, field, "v") });
    }
};

const Scalar = struct {
    ctype: []const u8,
    /// The call writing one field, $F standing for the field constant and $V for the value
    field: []const u8,
    /// The call writing one element of a packed field, $V standing for the value
    element: []const u8,
};

fn fill(arena: Allocator, template: []const u8, field: []const u8, value: []const u8) ![]const u8 {
    const with_field = try std.mem.replaceOwned(u8, arena, template, "$F", field);
    return std.mem.replaceOwned(u8, arena, with_field, "$V", value);
}

fn scalar(t: pb.Type) Scalar {
    return switch (t) {
        .int32, .@"enum" => .{
            .ctype = "int32_t",
            .field = "utrace_pb_field_varint(w, $F, (uint64_t)(int64_t)$V);",
            .element = "utrace_pb_varint(w, (uint64_t)(int64_t)$V);",
        },
        .int64 => .{
            .ctype = "int64_t",
            .field = "utrace_pb_field_varint(w, $F, (uint64_t)$V);",
            .element = "utrace_pb_varint(w, (uint64_t)$V);",
        },
        .uint32 => .{
            .ctype = "uint32_t",
            .field = "utrace_pb_field_varint(w, $F, $V);",
            .element = "utrace_pb_varint(w, $V);",
        },
        .uint64 => .{
            .ctype = "uint64_t",
            .field = "utrace_pb_field_varint(w, $F, $V);",
            .element = "utrace_pb_varint(w, $V);",
        },
        .bool => .{
            .ctype = "int",
            .field = "utrace_pb_field_varint(w, $F, $V ? 1u : 0u);",
            .element = "utrace_pb_varint(w, $V ? 1u : 0u);",
        },
        .sint32 => .{
            .ctype = "int32_t",
            .field = "utrace_pb_field_sint(w, $F, $V);",
            .element = "utrace_pb_varint(w, utrace_pb_zigzag($V));",
        },
        .sint64 => .{
            .ctype = "int64_t",
            .field = "utrace_pb_field_sint(w, $F, $V);",
            .element = "utrace_pb_varint(w, utrace_pb_zigzag($V));",
        },
        .fixed64 => .{
            .ctype = "uint64_t",
            .field = "utrace_pb_field_fixed64(w, $F, $V);",
            .element = "utrace_pb_le(w, $V, 8);",
        },
        .sfixed64 => .{
            .ctype = "int64_t",
            .field = "utrace_pb_field_fixed64(w, $F, (uint64_t)$V);",
            .element = "utrace_pb_le(w, (uint64_t)$V, 8);",
        },
        .fixed32 => .{
            .ctype = "uint32_t",
            .field = "utrace_pb_field_fixed32(w, $F, $V);",
            .element = "utrace_pb_le(w, $V, 4);",
        },
        .sfixed32 => .{
            .ctype = "int32_t",
            .field = "utrace_pb_field_fixed32(w, $F, (uint32_t)$V);",
            .element = "utrace_pb_le(w, (uint32_t)$V, 4);",
        },
        .double => .{
            .ctype = "double",
            .field = "utrace_pb_field_double(w, $F, $V);",
            .element = "utrace_pb_le(w, utrace_pb_double_bits($V), 8);",
        },
        .float => .{
            .ctype = "float",
            .field = "utrace_pb_field_float(w, $F, $V);",
            .element = "utrace_pb_le(w, utrace_pb_float_bits($V), 4);",
        },
        else => fatal("type {d} is not a scalar", .{@intFromEnum(t)}),
    };
}
